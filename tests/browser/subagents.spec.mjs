import { expect, test } from "@playwright/test";

test.use({ actionTimeout: 15_000 });

test("custom roles retain permissions, instructions, model and concurrency after save; deleting removes only the custom role", async ({ page }) => {
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/codey/tests/ui-browser.html?platform=windows");
  await expect(page.getByRole("button", { name: "已保存", exact: true })).toBeVisible({ timeout: 60_000 });
  await page.getByRole("button", { name: "子代理优化", exact: true }).click();
  const toggle = page.getByRole("switch", { name: "启用子代理优化", exact: true });
  await toggle.focus();
  await toggle.press("Space");
  await expect(toggle).toBeChecked();
  await expect(page.getByText("默认子代理", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "添加子代理", exact: true }).click();
  const role = page.locator("#custom_agent_1");
  await role.getByRole("textbox", { name: "名称", exact: true }).fill("测试审查员");
  await role.getByRole("textbox", { name: "用途说明", exact: true }).fill("检查边界条件和失败分支");
  await role.getByRole("textbox", { name: "角色指令", exact: true }).fill("只读调查并给出证据，不修改文件。");
  const access = role.getByRole("button", { name: /测试审查员读写能力/ });
  await access.click();
  await page.getByRole("option", { name: "可读写", exact: true }).click();
  await expect(page.getByRole("option", { name: "可读写", exact: true })).toHaveCount(0);
  await access.click();
  await page.getByRole("option", { name: "只读", exact: true }).click();
  await expect(page.getByRole("option", { name: "只读", exact: true })).toHaveCount(0);
  const model = role.getByRole("combobox", { name: "测试审查员模型", exact: true });
  await role.locator('[data-slot="combo-box-trigger"]').click();
  await page.getByRole("option", { name: "claude-opus-4-1", exact: true }).click();
  await expect(page.locator('[data-slot="combo-box-popover"]')).toHaveCount(0);
  await model.click();
  await model.fill("provider-fast-coder");
  await page.getByRole("option", { name: /provider-fast-coder/ }).click();
  await expect(page.locator('[data-slot="combo-box-popover"]')).toHaveCount(0);
  await role.getByRole("button", { name: /测试审查员思考深度/ }).click();
  await page.getByRole("option", { name: "高", exact: true }).click();
  await page.getByRole("textbox", { name: "最大并发子代理数量", exact: true }).fill("4");
  await page.getByRole("textbox", { name: "最大并发子代理数量", exact: true }).press("Tab");
  await page.getByRole("button", { name: "保存更改", exact: true }).click();
  await expect(page.getByRole("button", { name: "已保存", exact: true })).toBeDisabled();
  const stored = await page.evaluate(async () => (await window.__codexSessionDeleteBridge("/api/load_codey_config", {})).config);
  expect(stored.subagentMaxThreads).toBe(4);
  expect(stored.subagentRoles.custom_agent_1).toMatchObject({ name: "测试审查员", access: "readOnly", description: "检查边界条件和失败分支", developerInstructions: "只读调查并给出证据，不修改文件。" });
  expect(stored.subagentRoles.custom_agent_1.model).toMatch(/provider-fast-coder$/);
  expect(stored.subagentRoles.custom_agent_1.reasoningEffort).toBe("high");
  await page.getByRole("button", { name: "关闭配置", exact: true }).click();
  await page.getByRole("button", { name: "打开内嵌设置", exact: true }).click();
  await page.getByRole("button", { name: "子代理优化", exact: true }).click();
  await expect(role.getByRole("textbox", { name: "名称", exact: true })).toHaveValue("测试审查员");
  await role.scrollIntoViewIfNeeded();
  await page.screenshot({ path: "output/playwright/custom-subagents.png", fullPage: true });
  await page.setViewportSize({ width: 620, height: 900 });
  await role.scrollIntoViewIfNeeded();
  expect(await role.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: "output/playwright/custom-subagents-narrow.png", fullPage: true });
  await role.getByRole("button", { name: "删除测试审查员", exact: true }).click();
  await page.getByRole("button", { name: "保存更改", exact: true }).click();
  await expect(page.getByRole("button", { name: "已保存", exact: true })).toBeDisabled();
  const after = await page.evaluate(async () => (await window.__codexSessionDeleteBridge("/api/load_codey_config", {})).config);
  expect(after.subagentRoles.custom_agent_1).toBeUndefined();
  expect(after.subagentRoles.codey_worker).toEqual(stored.subagentRoles.codey_worker);
  expect(errors).toEqual([]);
});
